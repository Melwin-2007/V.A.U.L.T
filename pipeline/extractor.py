def extract_metrics(filing: Dict[str, Any]) -> List[Dict[str, Any]]:
    """Extract standard 10 financial metrics from XBRL and correlate verbatim HTML snippets."""
    cik = filing.get("cik", "0000000000")
    company = filing.get("company", "Unknown")
    fiscal_year = filing.get("fiscal_year", 2023)
    run_id = filing.get("run_id", "run_pending")
    source_url = filing.get("sec_url", f"https://www.sec.gov/edgar/data/{int(cik)}")
    xbrl_dir = filing.get("xbrl_dir")

    if not xbrl_dir or not Path(xbrl_dir).exists():
        # Fallback to stubs if no XBRL directory is available
        from pipeline.stubs import extract_metrics as stub_extract
        return stub_extract(filing)

    xb = XBRL.from_directory(Path(xbrl_dir))

    # Extract table blocks for snippet grounding
    tables = _extract_tables_from_rendered_statements(xb)
    if not tables:
        tables = _extract_tables_from_xbrl_textblocks(xb)

    records: List[Dict[str, Any]] = []
    raw_facts: Dict[str, Any] = {}

    for spec in METRIC_DEFINITIONS:
        name = spec["name"]
        fact = _extract_non_dim_fact(
            xb,
            spec["concepts"],
            period_type=spec["period_type"],
            metric_name=name,
            default_label=spec["label"],
            section_hint=spec["section"],
            label_keywords=spec["keywords"],
        )
        raw_facts[name] = fact

    # Handle derivation for total_liabilities if missing
    liab_derived = False
    if raw_facts["total_liabilities"] is None:
        le_fact = _extract_non_dim_fact(
            xb,
            ["us-gaap:LiabilitiesAndStockholdersEquity"],
            period_type="instant",
            metric_name="liabilities_and_equity",
            default_label="Total Liabilities and Stockholders' Equity",
            section_hint="Consolidated Balance Sheets",
            label_keywords=["liabilities and"],
        )
        eq_fact = raw_facts.get("shareholders_equity")
        if le_fact is not None and eq_fact is not None and le_fact.current_value is not None and eq_fact.current_value is not None:
            derived_val = le_fact.current_value - eq_fact.current_value
            prior_val = (
                le_fact.prior_value - eq_fact.prior_value
                if (le_fact.prior_value is not None and eq_fact.prior_value is not None)
                else None
            )
            from segmentation.extractor import RawMetricFact
            raw_facts["total_liabilities"] = RawMetricFact(
                metric="total_liabilities",
                label="Total liabilities (Derived: L&E - Equity)",
                concept="derived:LiabilitiesAndStockholdersEquity-StockholdersEquity",
                current_value=derived_val,
                prior_value=prior_val,
                period_label=le_fact.period_label,
                expected_year=le_fact.expected_year,
                fallback_scale=le_fact.fallback_scale,
                is_derived=True,
                s_label=0.85,
                source_section_hint="Consolidated Balance Sheets",
                label_keywords=["liabilities"],
            )
            liab_derived = True

    # Assemble records
    for spec in METRIC_DEFINITIONS:
        name = spec["name"]
        fact = raw_facts.get(name)

        if fact is None or fact.current_value is None:
            records.append({
                "metric_id": f"{run_id}:{name}",
                "run_id": run_id,
                "cik": cik,
                "company": company,
                "fiscal_year": fiscal_year,
                "metric_name": name,
                "value": None,
                "unit": spec["unit"],
                "period_start": None,
                "period_end": f"{fiscal_year}-12-31",
                "xbrl_tag": None,
                "source_snippet": "Metric not found in filing XBRL facts",
                "source_url": source_url,
                "confidence": 0.0,
                "confidence_breakdown": {"grounding": 0.0, "label": 0.0, "unit": 0.0, "yoy": 0.0},
                "is_derived": False,
                "flags": [],
                "status": "NEEDS_REVIEW",
                "escalation_reason": "Metric missing from filing XBRL facts",
                "final_value": None,
                "prior_value": None,
            })
            continue

        # Extract source snippet
        snippet = f"{fact.label}: {fact.current_value:,.2f}"
        if tables:
            try:
                found_snip, found_sec, uctx = find_matching_snippet_and_unit(
                    tables,
                    label_keywords=fact.label_keywords,
                    raw_value=fact.current_value,
                    fallback_scale=fact.fallback_scale,
                    expected_year=fact.expected_year,
                    default_section=spec["section"],
                )
                if found_snip:
                    snippet = found_snip
            except Exception:
                pass

        p_start = None
        p_end = f"{fiscal_year}-12-31"
        if "ended" in fact.period_label:
            p_end = fact.period_label.split("ended")[-1].strip()
        elif "of" in fact.period_label:
            p_end = fact.period_label.split("of")[-1].strip()

        records.append({
            "metric_id": f"{run_id}:{name}",
            "run_id": run_id,
            "cik": cik,
            "company": company,
            "fiscal_year": fiscal_year,
            "metric_name": name,
            "value": float(fact.current_value),
            "unit": spec["unit"],
            "period_start": p_start,
            "period_end": p_end,
            "xbrl_tag": fact.concept,
            "source_snippet": snippet,
            "source_url": source_url,
            "confidence": 0.0,
            "confidence_breakdown": {"grounding": 0.0, "label": 0.0, "unit": 0.0, "yoy": 0.0},
            "is_derived": fact.is_derived or (name == "total_liabilities" and liab_derived),
            "flags": [],
            "status": "NEEDS_REVIEW",
            "escalation_reason": None,
            "final_value": None,
            "prior_value": fact.prior_value,
        })

    return records

