def _resolve_companies(
    company_filter: Optional[str],
    source_data: Optional[dict[str, dict[str, dict]]] = None,
) -> dict[str, dict[str, dict]]:
    """Filter company dataset by name (case-insensitive) or return all."""
    dataset = source_data if source_data is not None else SAMPLE_COMPANIES
    if not company_filter:
        return dataset
    query = company_filter.strip().lower()
    matched = {
        name: data
        for name, data in dataset.items()
        if name.lower() == query or query in name.lower()
    }
    return matched


def run_demo(
    company_filter: Optional[str] = None,
    file_path: Optional[str] = None,
) -> int:
    source_data = (
        json.loads(Path(file_path).read_text(encoding="utf-8"))
        if file_path
        else SAMPLE_COMPANIES
    )
    companies = _resolve_companies(company_filter, source_data=source_data)
    if not companies:
        available = ", ".join(source_data.keys())
        print(
            f"Company {company_filter!r} not found in dataset. "
            f"Available companies: {available}",
            file=sys.stderr,
        )
        return 1

    thresholds = load_thresholds()
    print("=" * 116)
    print(
        f"{'COMPANY':26} | {'METRIC':20} | {'STATUS':6} | {'YOY %':>11} | "
        f"{'THRESH':>6} | {'CONF':>9} | REASON"
    )
    print("=" * 116)

    total_escalations = []
    for company, metrics in companies.items():
        output = yoy_validation_node(
            {
                "company": company,
                "metrics": metrics,
                "thresholds": thresholds,
            }
        )
        for res in output["validation_results"]:
            status_label = {
                "ok": "PASS",
                "warn": "WARN",
                "fail": "FAIL",
                "not_applicable": "N/A",
            }.get(res["severity"], "N/A")
            pct_str = (
                "N/A" if res["pct_change"] is None else f"{res['pct_change']:+.2f}%"
            )
            thresh_str = (
                "N/A"
                if res["threshold_used"] is None
                else f"{res['threshold_used']:.0f}%"
            )
            orig_conf = metrics[res["metric"]]["confidence"]
            conf_str = f"{orig_conf:.2f}->{res['adjusted_confidence']:.2f}"
            print(
                f"{company:26} | {res['metric']:20} | {status_label:6} | "
                f"{pct_str:>11} | {thresh_str:>6} | {conf_str:>9} | {explain(res)}"
            )
        total_escalations.extend(output["escalations"])

    print("=" * 116)
    print(f"\nEscalated for Human-in-the-Loop Review: {len(total_escalations)} item(s)")
    for esc in total_escalations:
        print(
            f" - [{esc['key']}] severity={esc['severity']} | action={esc['suggested_action']}"
        )
    return 0


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="Run YoY validation demo for all sample companies or one specific company."
    )
    parser.add_argument(
        "company_pos",
        nargs="?",
        help="Optional company name (e.g. Apple, Microsoft, Tesla, Walmart, Coca-Cola).",
    )
    parser.add_argument(
        "-c",
        "--company",
        help="Filter to a specific company (case-insensitive).",
    )
    parser.add_argument(
        "-f",
        "--file",
        help="Optional path to a JSON file mapping company -> metrics.",
    )
    parser.add_argument(
        "--list",
        action="store_true",
        help="List available companies and exit.",
    )
    args = parser.parse_args(argv)

    if args.list:
        data = (
            json.loads(Path(args.file).read_text(encoding="utf-8"))
            if args.file
            else SAMPLE_COMPANIES
        )
        print("Available companies:", ", ".join(data.keys()))
        return 0

    selected = args.company or args.company_pos
    return run_demo(selected, file_path=args.file)


if __name__ == "__main__":
    sys.exit(main())

